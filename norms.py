"""Границы суточной нормы калорий и формулировки для порций (без тяжёлых зависимостей)."""

CALORIE_FLOOR = 1200      # норма никогда не опускается ниже этого значения и ниже базового обмена
PORTION_MAX = 2.0         # порции в рецептах советуем увеличивать не больше чем вдвое

FLOOR_NOTE = ("ℹ️ Норма ограничена нижней безопасной границей (базовый обмен), "
              "поэтому дефицит получился мягче расчётного.")

# Множитель порции -> как об этом сказать человеку (шаг 0,25)
_FACTOR_PHRASES = {
    1.25: "на четверть больше",
    1.5: "в полтора раза больше",
    1.75: "почти вдвое больше",
    2.0: "вдвое больше",
}


def basal_metabolism(weight: float, body_fat: float) -> float:
    """Базовый обмен по Кэтчу-Макардлу (та же формула, что в расчёте нормы)."""
    return 370 + 21.6 * weight * (1 - body_fat / 100)


def min_daily_calories(weight: float, body_fat: float) -> int:
    """Нижняя граница нормы: не меньше базового обмена и не меньше CALORIE_FLOOR."""
    return int(round(max(CALORIE_FLOOR, basal_metabolism(weight, body_fat))))


def factor_phrase(factor: float):
    """«вдвое больше», «в полтора раза больше»… или None, если увеличивать порции не нужно."""
    return _FACTOR_PHRASES.get(round(factor * 4) / 4)
