OPERATOR_CONTACT = getattr(config, "OPERATOR_CONTACT", "") or SUPPORT_EMAIL or "через сообщение администратору бота"


def _md(text: str) -> str:
    return text.replace("_", "\\_")


def support_line() -> str:
    """Строка «Вопросы — на почту» для экранов бота; пустая, если почта не задана в config.py."""
    return f"\n\n✉️ Вопросы по боту и оплате: {_md(SUPPORT_EMAIL)}" if SUPPORT_EMAIL else ""


def support_text() -> str:
    if SUPPORT_EMAIL:
        return (f"✉️ *Связь с нами*\n\nПишите на почту: {_md(SUPPORT_EMAIL)}\n\n"
                "Чтобы мы быстрее помогли, укажите, что случилось, и свой ID в Telegram (его покажет команда /myid).")
    return "✉️ Напишите администратору бота — контакт указан в описании бота."


