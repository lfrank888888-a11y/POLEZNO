def consent_kb(types):
    kb = types.InlineKeyboardMarkup(row_width=1)
    kb.add(types.InlineKeyboardButton("✅ Принимаю", callback_data="consent_yes"),
           types.InlineKeyboardButton("📄 Прочитать политику", callback_data="privacy_show"))
    return kb


def delete_confirm_kb(types):
    kb = types.InlineKeyboardMarkup(row_width=2)
    kb.add(types.InlineKeyboardButton("🗑 Да, удалить", callback_data="erase_confirm"),
           types.InlineKeyboardButton("Отмена", callback_data="erase_cancel"))
    return kb
