def merge_extra_menus(sample_menus: dict) -> dict:
    """Добавляет блюда из EXTRA_MENUS в SAMPLE_MENUS (на месте, без дублей)."""
    for goal, categories in EXTRA_MENUS.items():
        for category, items in categories.items():
            target = sample_menus.setdefault(goal, {}).setdefault(category, [])
            target.extend(item for item in items if item not in target)
    return sample_menus
