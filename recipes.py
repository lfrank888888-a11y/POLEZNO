def get_recipe_by_name(name: str) -> dict:
    clean = name.split("—")[0].strip()
    clean = "".join(c for c in clean if not (0x1F300 <= ord(c) <= 0x1F9FF or 0x2600 <= ord(c) <= 0x26FF)).strip()
    return RECIPES.get(clean)


# Хэш -> точное название блюда. Строится один раз при импорте модуля и
# используется, чтобы найти рецепт по callback_data вида "recipe_<hash>",
# которое формирует menu_generator.get_menu_with_recipe_kb().
RECIPE_HASH_MAP = {hashlib.md5(name.encode('utf-8')).hexdigest()[:8]: name for name in RECIPES}


def get_recipe_by_hash(short_hash: str):
    """Вернуть (название_блюда, рецепт) по хэшу из callback_data, либо (None, None)."""
    name = RECIPE_HASH_MAP.get(short_hash)
    if not name:
        return None, None
    return name, RECIPES.get(name)


# Во сколько раз крупа/паста прибавляет в весе после варки (средние значения, поэтому «≈»)
_COOK_RATIO = (
    ("рисов", 2.2), ("рис", 3.0), ("гречк", 2.5), ("гречн", 2.5), ("булгур", 2.5), ("киноа", 3.0), ("пшен", 3.0),
    ("кускус", 2.5), ("перлов", 3.0), ("чечевиц", 2.5), ("паста", 2.2), ("макарон", 2.2),
    ("спагетти", 2.2), ("лапша", 2.2),
)
_COOKED_WORDS = ("варён", "варен", "отварн", "готов", "консерв")
_PORRIDGE_WORDS = ("каш", "суп", "овсян", "с молоком")
_RAW_QTY = re.compile(r"^\s*(\d+(?:[.,]\d+)?)\s*г\b")


def _cooked_hint(ing: str, dish_name: str):
    """Для «Рис — 60 г» -> «Рис — 60 г (≈ 180 г варёного)». None, если пересчёт не нужен."""
    low_dish = dish_name.lower()
    if any(w in low_dish for w in _PORRIDGE_WORDS):
        return None  # каша и суп: крупа впитывает жидкость из рецепта, отдельного гарнира нет
    name, sep, qty = ing.partition("—")
    low_name = name.lower()
    if not sep or any(w in (low_name + qty.lower()) for w in _COOKED_WORDS):
        return None
    ratio = next((r for stem, r in _COOK_RATIO if low_name.strip().startswith(stem)), None)
    m = _RAW_QTY.match(qty)
    if not ratio or not m:
        return None
    grams = float(m.group(1).replace(",", "."))
    cooked = int(round(grams * ratio / 10.0)) * 10
    word = "варёной" if low_name.strip().startswith(("паста", "лапша")) else "варёного"
    ing = ing.rstrip()
    if ing.endswith("(сухая)"):
        return f"{ing[:-1]}, ≈ {cooked} г {word})"
    return f"{ing} (≈ {cooked} г {word})"


def format_recipe(recipe: dict, dish_name: str) -> str:
    lines = [f"📖 *{dish_name}*", f"⏱ Время: {recipe['time']} | 🍽 Порций: {recipe['portions']}", "", "🛒 *Ингредиенты:*"]
    converted = False
    for ing in recipe['ingredients']:
        hint = _cooked_hint(ing, dish_name)
        converted = converted or bool(hint)
        lines.append(f"   • {hint or ing}")
    if converted:
        lines.append("   _Крупы и паста указаны в сухом виде; в скобках — вес после варки._")
    lines.append("")
    lines.append("👨‍🍳 *Приготовление:*")
    for step in recipe['steps']:
        lines.append(f"   {step}")
    lines.append("")
    lines.append(recipe['tip'])
    return "\n".join(lines)
